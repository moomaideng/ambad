/**
* @brief Function implementing the UartCommsTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartUartCommsTask */
void StartUartCommsTask(void *argument)
{
  /* USER CODE BEGIN StartUartCommsTask */
  char tx_buf[48];

  /* Infinite loop */
  for(;;) {
    int len = snprintf(tx_buf, sizeof(tx_buf), "J,%d,%d,%d\r\n", joy_state.jx,
        joy_state.jy, joy_state.btn);
    HAL_UART_Transmit(&huart2, (uint8_t *)tx_buf, (uint16_t)len, 20);
    osDelay(40);
  }
  /* USER CODE END StartUartCommsTask */
}

