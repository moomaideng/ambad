static int16_t map_axis(uint32_t raw) {
  int32_t centered = (int32_t)raw - 2048;
  if (centered > -150 && centered < 150) return 0;
  int32_t scaled = (centered * 100) / 1950;
  if (scaled > 100) scaled = 100;
  if (scaled < -100) scaled = -100;
  return (int16_t)scaled;
}

